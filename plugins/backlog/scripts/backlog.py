#!/usr/bin/env python3
"""Keeps a repository backlog consistent for coding agents (Claude Code, Grok, Copilot CLI).

Layout, at the repository root:
    backlog/<id>-<slug>.md   one open item per file
    backlog/history.jsonl    append-only: finished items, decisions, corrections
    BACKLOG.md               optional index: free text plus a generated list of blocked and open items
                             (`backlog init --index` creates it; `backlog list` shows the same without a file)

Agents change the backlog only through this script, never by editing history.jsonl or the
generated list by hand. `backlog <command> --help` describes each command.
Exit codes: 0 ok, 1 nothing to do (`next`) or problems found (`check`), 2 error.
"""
from __future__ import annotations

import argparse
import contextlib
import datetime
import json
import pathlib
import re
import subprocess
import sys

try:
    import fcntl
except ImportError:  # Windows has no fcntl: no file lock there, so run one agent at a time per checkout
    fcntl = None

ITEM_NAME = re.compile(r"^(\d+)-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DONE_WHEN = re.compile(r"^\*\*Done when:?\*\*:?[ \t]*(.*)$")
BLOCKED = re.compile(r"^\*\*Blocked:\*\*[ \t]*(.+)$", re.M)
DEPENDS = re.compile(r"^\*\*Depends on:\*\*[ \t]*(.+)$", re.M)
START = "<!-- backlog:start"
START_LINE = "<!-- backlog:start (generated by `backlog render`; do not edit by hand) -->"
END = "<!-- backlog:end -->"
REQUIRED = {
    "completed": ("id", "title", "recorded", "source", "body"),
    "section": ("part", "title", "recorded", "source", "body"),
    "correction": ("refersTo", "title", "recorded", "source", "body"),
}
INTRO = """# Backlog

Open work is one file per item in [backlog/](./backlog/). Decisions, finished items and corrections
are in [backlog/history.jsonl](./backlog/history.jsonl), which is append-only. The lists below are
generated by `backlog render`; change the items, not the lists.
"""


class BacklogError(Exception):
    pass


class Item:
    def __init__(self, path: pathlib.Path):
        match = ITEM_NAME.match(path.name)
        if not match:
            raise BacklogError(f"{path.name}: not an item file name (<id>-<slug>.md)")
        self.path = path
        self.id = int(match.group(1))
        self.slug = match.group(2)
        self.text = path.read_text(encoding="utf-8")
        first = self.text.split("\n", 1)[0]
        self.title = first[2:].strip() if first.startswith("# ") else ""
        blocked = BLOCKED.search(self.text)
        self.blocked = blocked.group(1).strip() if blocked else ""
        depends = DEPENDS.search(self.text)
        self.depends = [int(n) for n in re.findall(r"\d+", depends.group(1))] if depends else []
        self.checks = done_checks(self.text)

    @property
    def rel(self) -> str:
        return f"backlog/{self.path.name}"


def done_checks(text: str) -> list[str]:
    """The checks under **Done when**: text on the same line, then each top-level bullet."""
    lines = text.splitlines()
    for index, line in enumerate(lines):
        match = DONE_WHEN.match(line)
        if match:
            break
    else:
        return []
    checks = [match.group(1).strip()] if match.group(1).strip() else []
    for line in lines[index + 1:]:
        if line.startswith("#") or line.startswith("**"):
            break
        if line.startswith("- "):
            checks.append(line[2:].strip())
        elif checks and line[:1] in (" ", "\t") and line.strip():
            checks[-1] += " " + line.strip()
    return checks


def today() -> str:
    return datetime.date.today().isoformat()


def find_root(start: pathlib.Path) -> pathlib.Path:
    for directory in (start, *start.parents):
        if (directory / "backlog" / "history.jsonl").is_file():
            return directory
    raise BacklogError("no backlog/history.jsonl here or above; run `backlog init` at the repository root")


def history_path(root: pathlib.Path) -> pathlib.Path:
    return root / "backlog" / "history.jsonl"


def read_history(root: pathlib.Path) -> list[dict]:
    entries = []
    for number, line in enumerate(history_path(root).read_text(encoding="utf-8").splitlines(), 1):
        try:
            entries.append(json.loads(line))
        except json.JSONDecodeError as error:
            raise BacklogError(f"history.jsonl line {number} is not JSON ({error}); run `backlog check`")
    return entries


def read_items(root: pathlib.Path) -> list[Item]:
    items = [Item(p) for p in (root / "backlog").glob("*.md") if ITEM_NAME.match(p.name)]
    return sorted(items, key=lambda item: item.id)


def completed_ids(history: list[dict]) -> set[int]:
    return {e["id"] for e in history if e.get("kind") == "completed" and isinstance(e.get("id"), int)}


def get_item(root: pathlib.Path, item_id: int) -> Item:
    for item in read_items(root):
        if item.id == item_id:
            return item
    if item_id in completed_ids(read_history(root)):
        raise BacklogError(f"item {item_id} is already finished (see `backlog show {item_id}`)")
    raise BacklogError(f"no open item {item_id}")


def next_id(root: pathlib.Path) -> int:
    ids = [e["id"] for e in read_history(root) if isinstance(e.get("id"), int)]
    ids += [item.id for item in read_items(root)]
    return max(ids, default=0) + 1


@contextlib.contextmanager
def locked(root: pathlib.Path):
    """Serializes writers in one checkout (parallel agents). Without fcntl (Windows) it does not lock."""
    if fcntl is None:
        yield
        return
    with open(history_path(root), "rb") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def append(root: pathlib.Path, entry: dict) -> int:
    path = history_path(root)
    data = path.read_bytes()
    if data and not data.endswith(b"\n"):
        raise BacklogError("history.jsonl does not end with a newline; run `backlog check`")
    seq = data.count(b"\n") + 1
    with open(path, "ab") as handle:
        handle.write((json.dumps({"seq": seq, **entry}, ensure_ascii=False) + "\n").encode("utf-8"))
    return seq


def read_input(source: str | None) -> str:
    text = sys.stdin.read() if source in (None, "-") else pathlib.Path(source).read_text(encoding="utf-8")
    if not text.strip():
        raise BacklogError("empty input (pass the text on stdin or with --file)")
    return text


def item_problems(text: str, known_ids: set[int]) -> list[str]:
    problems = []
    if not text.startswith("# ") or not text.split("\n", 1)[0][2:].strip():
        problems.append("the first line must be `# <title>`")
    if not done_checks(text):
        problems.append("no **Done when** check (a line `**Done when**` followed by `- ` bullets)")
    depends = DEPENDS.search(text)
    for dep in (int(n) for n in re.findall(r"\d+", depends.group(1))) if depends else []:
        if dep not in known_ids:
            problems.append(f"Depends on {dep}: no such item")
    return problems


def render_block(root: pathlib.Path) -> str:
    items = read_items(root)
    done = completed_ids(read_history(root))
    lines = [START_LINE, "## Blocked", ""]
    lines += [f"- [{i.id} {i.title}]({i.rel}): {i.blocked}" for i in items if i.blocked] or ["None."]
    lines += ["", "## Open", ""]
    for item in items:
        waits = [d for d in item.depends if d not in done]
        notes = (["blocked"] if item.blocked else []) + ([f"after {', '.join(map(str, waits))}"] if waits else [])
        lines.append(f"- [{item.id} {item.title}]({item.rel})" + (f" ({'; '.join(notes)})" if notes else ""))
    if not items:
        lines.append("None.")
    lines.append(END)
    return "\n".join(lines)


def split_backlog_md(text: str) -> tuple[str, str, str] | None:
    start = text.find(START)
    end = text.find(END, start)
    if start < 0 or end < 0:
        return None
    return text[:start], text[start:end + len(END)], text[end + len(END):]


def write_backlog_md(root: pathlib.Path, create: bool = False) -> bool:
    """Refreshes the generated list of the optional BACKLOG.md index; returns whether there is one.

    A BACKLOG.md without the markers is an ordinary file and is left alone. With `create`, a missing file is
    written, and a file without the markers is an error (the caller asked for an index there).
    """
    path = root / "BACKLOG.md"
    if path.exists():
        parts = split_backlog_md(path.read_text(encoding="utf-8"))
        if parts is None:
            if create:
                raise BacklogError("BACKLOG.md exists without the generated list; add a line `<!-- backlog:start -->` and a line "
                                   "`<!-- backlog:end -->` where the lists go (remove the old lists), then run `backlog render`")
            return False
        before, _, after = parts
    elif create:
        before, after = INTRO + "\n", "\n"
    else:
        return False
    path.write_text(before + render_block(root) + after, encoding="utf-8")
    return True


def state(item: Item, done: set[int]) -> str:
    if item.blocked:
        return "blocked"
    return "waiting" if any(d not in done for d in item.depends) else "open"


def item_json(item: Item, done: set[int]) -> dict:
    return {"id": item.id, "title": item.title, "path": item.rel, "state": state(item, done),
            "blocked": item.blocked, "dependsOn": item.depends,
            "waitingFor": [d for d in item.depends if d not in done], "checks": len(item.checks)}


# Commands


def cmd_init(args) -> int:
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=args.C, capture_output=True, text=True, check=True)
        root = pathlib.Path(top.stdout.strip())
    except (subprocess.CalledProcessError, FileNotFoundError):
        root = pathlib.Path(args.C).resolve()
    (root / "backlog").mkdir(exist_ok=True)
    history_path(root).touch()
    if args.index:
        write_backlog_md(root, create=True)
    print(f"backlog ready in {root}")
    return 0


def cmd_add(args) -> int:
    if not SLUG.match(args.slug):
        raise BacklogError("--slug must be lowercase words joined by hyphens, e.g. database-abstraction")
    text = read_input(args.file).strip() + "\n"
    root = find_root(args.C)
    with locked(root):
        known = {item.id for item in read_items(root)} | completed_ids(read_history(root))
        problems = item_problems(text, known)
        if problems:
            raise BacklogError("item not added: " + "; ".join(problems))
        new_id = next_id(root)
        path = root / "backlog" / f"{new_id}-{args.slug}.md"
        path.write_text(text, encoding="utf-8")
        write_backlog_md(root)
    print(json.dumps({"id": new_id, "path": f"backlog/{path.name}"}) if args.json else f"{new_id} backlog/{path.name}")
    return 0


def cmd_list(args) -> int:
    root = find_root(args.C)
    done = completed_ids(read_history(root))
    items = read_items(root)
    if args.json:
        print(json.dumps([item_json(i, done) for i in items], ensure_ascii=False, indent=1))
    for item in [] if args.json else items:
        print(f"{item.id:>4}  {state(item, done):<8} {item.title}")
        if item.blocked:
            print(f"      blocked: {item.blocked}")
        waits = [d for d in item.depends if d not in done]
        if waits:
            print(f"      waits for: {', '.join(map(str, waits))}")
    return 0


def cmd_next(args) -> int:
    root = find_root(args.C)
    done = completed_ids(read_history(root))
    items = read_items(root)
    workable = [i for i in items if state(i, done) == "open"]
    if not workable:
        if args.json:
            print("null")
        print(f"no workable item ({len(items)} open, all blocked or waiting)", file=sys.stderr)
        return 1
    item = workable[0]
    print(json.dumps(item_json(item, done), ensure_ascii=False) if args.json else f"{item.id} {item.rel}")
    return 0


def cmd_show(args) -> int:
    root = find_root(args.C)
    for item in read_items(root):
        if item.id == args.id:
            print(item.text, end="")
            return 0
    for entry in reversed(read_history(root)):
        if entry.get("kind") == "completed" and entry.get("id") == args.id:
            print(f"<!-- finished: seq {entry['seq']}, recorded {entry.get('recorded')} -->\n{entry['body']}", end="")
            return 0
    raise BacklogError(f"no item {args.id}")


def cmd_next_id(args) -> int:
    print(next_id(find_root(args.C)))
    return 0


def cmd_block(args) -> int:
    root = find_root(args.C)
    with locked(root):
        item = get_item(root, args.id)
        text = re.sub(r"^\*\*Blocked:\*\*[^\n]*\n\n?", "", item.text, flags=re.M)
        if args.reason:
            head, _, rest = text.partition("\n")
            text = f"{head}\n\n**Blocked:** {' '.join(args.reason.split())}\n" + (rest if rest.startswith("\n") else "\n" + rest)
        item.path.write_text(text, encoding="utf-8")
        write_backlog_md(root)
    print(f"{args.id} {'blocked' if args.reason else 'unblocked'}")
    return 0


def cmd_finish(args) -> int:
    root = find_root(args.C)
    data = json.loads(read_input(args.verification))
    with locked(root):
        item = get_item(root, args.id)
        history = read_history(root)
        if item.blocked:
            raise BacklogError(f"item {item.id} is blocked ({item.blocked}); it can't be finished")
        waits = [d for d in item.depends if d not in completed_ids(history)]
        if waits:
            raise BacklogError(f"item {item.id} depends on open items {waits}")
        if isinstance(data, dict) and data.get("allMet") is False:
            raise BacklogError("the verification says not every check is met")
        checks = data.get("checks") if isinstance(data, dict) else data
        if not isinstance(checks, list) or len(checks) != len(item.checks):
            raise BacklogError(f"item {item.id} has {len(item.checks)} Done-when checks; the verification must list "
                               f"each one, in order (got {len(checks) if isinstance(checks, list) else 'no list'})")
        verification = []
        for number, (check, text) in enumerate(zip(checks, item.checks), 1):
            if not isinstance(check, dict) or not str(check.get("evidence", "")).strip():
                raise BacklogError(f"check {number} has no evidence")
            if check.get("met") is False:
                raise BacklogError(f"check {number} is not met: {check.get('gap') or text}")
            verification.append({"check": str(check.get("check") or text), "evidence": str(check["evidence"]).strip()})
        seq = append(root, {"kind": "completed", "id": item.id, "title": item.title, "recorded": today(),
                            "source": args.source or item.rel, "body": item.text, "verification": verification})
        item.path.unlink()
        write_backlog_md(root)
    print(f"{item.id} finished (history seq {seq})")
    return 0


def cmd_decide(args) -> int:
    if not SLUG.match(args.part):
        raise BacklogError("--part must be lowercase words joined by hyphens, e.g. out-of-scope")
    body = read_input(args.file).strip()
    if not body.startswith("#"):
        body = f"## {args.title}\n\n{body}"
    root = find_root(args.C)
    with locked(root):
        seq = append(root, {"kind": "section", "part": args.part, "title": args.title, "recorded": today(),
                            "source": args.source, "body": body + "\n"})
    print(f"part {args.part} recorded (history seq {seq})")
    return 0


def cmd_correct(args) -> int:
    body = read_input(args.file).strip() + "\n"
    root = find_root(args.C)
    with locked(root):
        referred = next((e for e in read_history(root) if e.get("seq") == args.refers_to), None)
        if referred is None:
            raise BacklogError(f"no history line with seq {args.refers_to}")
        key = "part" if "part" in referred else "id"
        seq = append(root, {"kind": "correction", "refersTo": args.refers_to, key: referred.get(key),
                            "title": referred.get("title", ""), "recorded": today(), "source": args.source, "body": body})
    print(f"correction of seq {args.refers_to} recorded (history seq {seq})")
    return 0


def latest_parts(history: list[dict]) -> dict[str, dict]:
    parts = {}
    for entry in history:
        if entry.get("kind") == "section":
            parts[entry["part"]] = entry
    return parts


def cmd_parts(args) -> int:
    parts = latest_parts(read_history(find_root(args.C)))
    rows = [{"part": k, "title": v["title"], "seq": v["seq"], "recorded": v.get("recorded")} for k, v in sorted(parts.items())]
    if args.json:
        print(json.dumps(rows, ensure_ascii=False, indent=1))
    for row in [] if args.json else rows:
        print(f"{row['part']:<28} {row['title']}")
    return 0


def cmd_part(args) -> int:
    history = read_history(find_root(args.C))
    entry = latest_parts(history).get(args.part)
    if entry is None:
        raise BacklogError(f"no part {args.part} (see `backlog parts`)")
    corrections = [e for e in history if e.get("kind") == "correction" and e.get("refersTo") == entry["seq"]]
    print(f"<!-- part {args.part}: seq {entry['seq']}, recorded {entry.get('recorded')}, source {entry.get('source')} -->")
    print(entry["body"], end="" if entry["body"].endswith("\n") else "\n")
    for correction in corrections:
        print(f"\n<!-- correction seq {correction['seq']} -->\n{correction['body']}", end="")
    return 0


def cmd_render(args) -> int:
    root = find_root(args.C)
    with locked(root):
        if not write_backlog_md(root):
            print("no BACKLOG.md index to render (it is optional; `backlog init --index` creates one). "
                  "`backlog list` shows the open items.", file=sys.stderr)
    return 0


def cmd_check(args) -> int:
    root = find_root(args.C)
    problems = []
    raw = history_path(root).read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as error:
        print(f"history.jsonl: not UTF-8 ({error})")
        return 1
    if raw and not raw.endswith(b"\n"):
        problems.append("history.jsonl: the last line does not end with a newline")
    history = []
    for number, line in enumerate(text.splitlines(), 1):
        try:
            entry = json.loads(line)
        except json.JSONDecodeError as error:
            problems.append(f"history.jsonl line {number}: not JSON ({error})")
            continue
        if not isinstance(entry, dict):
            problems.append(f"history.jsonl line {number}: not an object")
            continue
        history.append(entry)
        if entry.get("seq") != number:
            problems.append(f"history.jsonl line {number}: seq is {entry.get('seq')!r}, must be the line number")
        kind = entry.get("kind")
        if kind not in REQUIRED:
            problems.append(f"history.jsonl line {number}: unknown kind {kind!r}")
            continue
        missing = [f for f in REQUIRED[kind] if f not in entry]
        if missing:
            problems.append(f"history.jsonl line {number}: {kind} without {', '.join(missing)}")
        if kind == "correction" and not (isinstance(entry.get("refersTo"), int) and 0 < entry["refersTo"] < number):
            problems.append(f"history.jsonl line {number}: refersTo must name an earlier seq")
    done = completed_ids(history)
    known = set(done)
    seen = {}
    for path in sorted((root / "backlog").iterdir()):
        if path.name == "history.jsonl":
            continue
        if not ITEM_NAME.match(path.name):
            problems.append(f"backlog/{path.name}: not an item file (<id>-<slug>.md)")
            continue
        item = Item(path)
        known.add(item.id)
        if item.id in seen:
            problems.append(f"{item.rel}: id {item.id} also used by {seen[item.id]}")
        seen[item.id] = item.rel
        if item.id in done:
            problems.append(f"{item.rel}: item {item.id} is already finished in history.jsonl")
    for item in read_items(root):
        problems += [f"{item.rel}: {p}" for p in item_problems(item.text, known)]
        if item.id in item.depends:
            problems.append(f"{item.rel}: depends on itself")
    md = root / "BACKLOG.md"
    parts = split_backlog_md(md.read_text(encoding="utf-8")) if md.exists() else None
    if parts is not None and not problems and parts[1] != render_block(root):  # the index is optional, a stale one is not
        problems.append("BACKLOG.md: the generated list is out of date (run `backlog render`)")
    for problem in problems:
        print(problem)
    if not problems:
        print(f"ok: {len(seen)} open items, {len(history)} history lines")
    return 1 if problems else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="backlog", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-C", type=pathlib.Path, default=pathlib.Path.cwd(), metavar="DIR", help="run as if started in DIR")
    sub = parser.add_subparsers(dest="command", required=True)

    def command(name, func, help_text):
        p = sub.add_parser(name, help=help_text, description=help_text)
        p.set_defaults(func=func)
        return p

    p = command("init", cmd_init, "create backlog/ and history.jsonl at the git root (keeps what exists); --index also creates BACKLOG.md")
    p.add_argument("--index", action="store_true", help="also create the optional BACKLOG.md index with the generated list")
    p = command("add", cmd_add, "add an item: Markdown on stdin or --file; prints the new id and path")
    p.add_argument("--slug", required=True, help="short English name, e.g. database-abstraction")
    p.add_argument("--file", help="item text (default: stdin)")
    p.add_argument("--json", action="store_true")
    p = command("list", cmd_list, "list open items with their state (open, waiting, blocked)")
    p.add_argument("--json", action="store_true")
    p = command("next", cmd_next, "the lowest-id item that is neither blocked nor waiting; exit 1 if there is none")
    p.add_argument("--json", action="store_true")
    p = command("show", cmd_show, "print an open item, or the text of a finished one")
    p.add_argument("id", type=int)
    command("next-id", cmd_next_id, "print the id the next item gets")
    p = command("block", cmd_block, "mark an item blocked: what is needed from outside the repo, and from whom")
    p.add_argument("id", type=int)
    p.add_argument("reason")
    p = command("unblock", cmd_block, "remove the Blocked line from an item")
    p.add_argument("id", type=int)
    p.set_defaults(reason="")
    p = command("finish", cmd_finish, "close a verified item: append it to history.jsonl, delete its file, refresh the BACKLOG.md index if there is one")
    p.add_argument("id", type=int)
    p.add_argument("--verification", default="-", help='JSON on stdin or in this file: [{"check", "evidence"}] '
                   'or the backlog-verifier output {"allMet", "checks": [...]}, one entry per Done-when check, in order')
    p.add_argument("--source", help="where the body came from (default: the item file)")
    p = command("decide", cmd_decide, "append a decision or other standing part (the full new text) to history.jsonl")
    p.add_argument("--part", required=True, help="stable slug; reuse it to replace a part")
    p.add_argument("--title", required=True)
    p.add_argument("--source", required=True, help="where it came from: a user message, an item, a review")
    p.add_argument("--file", help="body (default: stdin)")
    p = command("correct", cmd_correct, "append a correction of an earlier history line")
    p.add_argument("--refers-to", type=int, required=True, help="seq of the line that was wrong")
    p.add_argument("--source", required=True)
    p.add_argument("--file", help="what was wrong and what is right (default: stdin)")
    p = command("parts", cmd_parts, "list the current decisions and other parts")
    p.add_argument("--json", action="store_true")
    p = command("part", cmd_part, "print the current text of a part, with corrections of it")
    p.add_argument("part")
    command("render", cmd_render, "regenerate the lists in the optional BACKLOG.md index (nothing to do without one)")
    command("check", cmd_check, "validate history.jsonl, the item files and the BACKLOG.md index if there is one; exit 1 on problems")

    args = parser.parse_args(argv)
    # The history and the items are UTF-8; the console of Windows is not (cp1252): text in and out must not depend on it.
    for stream in (sys.stdin, sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    try:
        return args.func(args)
    except BacklogError as error:
        print(f"backlog: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
